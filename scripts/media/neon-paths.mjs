// The neon signs' outlines, from Neonderthaw (a script drawn as neon tubes,
// OFL): each word becomes its outlines in writing order (one SVG path each:
// a dash pattern restarts at every outline, so the page draws them one by one).
//
//   node scripts/media/neon-paths.mjs   → src/app/neon-paths.ts
import opentype from "opentype.js";
import { writeFileSync } from "node:fs";

const WORDS = ["AI Agent", "Business App", "Studio", "Every Business", "Human Touch", "Websites", "Danielor"];
const font = opentype.loadSync(new URL("../fonts/Neonderthaw-Regular.ttf", import.meta.url).pathname);
const out = {};
for (const w of WORDS) {
  const p = font.getPath(w, 0, 0, 200);
  const b = p.getBoundingBox();
  const pad = 24;
  const shifted = font.getPath(w, pad - b.x1, pad - b.y1, 200);
  out[w] = { parts: shifted.toPathData(1).split(/(?=M)/).filter((x) => x.trim()), w: Math.ceil(b.x2 - b.x1 + 2 * pad), h: Math.ceil(b.y2 - b.y1 + 2 * pad) };
}
writeFileSync(
  new URL("../../src/film/neon-paths.ts", import.meta.url).pathname,
  `// generated by scripts/media/neon-paths.mjs, do not edit\nexport const NEON: Record<string, { parts: string[]; w: number; h: number }> = ${JSON.stringify(out, null, 1)};\n`,
);
console.log(Object.entries(out).map(([k, v]) => `${k}: ${v.w}x${v.h}, ${v.parts.length} outlines`).join("\n"));
