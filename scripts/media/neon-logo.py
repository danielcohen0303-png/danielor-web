# Adele's logo (her own hand: "Adele Beauty Clinic") as a neon sign: the black strokes are
# traced into closed outlines, so the page draws each stroke as a tube (both edges, like the
# Neonderthaw signs), in writing order from left to right.
#
#   python3 scripts/media/neon-logo.py   -> src/app/neon-logo.ts
import json, os
import cv2
import numpy as np

here = os.path.dirname(os.path.abspath(__file__))
img = cv2.imread(os.path.join(here, "../fonts/adele-logo.png"), cv2.IMREAD_GRAYSCALE)
ink = (img < 140).astype(np.uint8) * 255
ys, xs = np.nonzero(ink)
pad = 24
x0, y0, x1, y1 = xs.min() - pad, ys.min() - pad, xs.max() + pad, ys.max() + pad
ink = ink[y0:y1, x0:x1]
contours, hier = cv2.findContours(ink, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_NONE)
hier = hier[0]

def path(c):
    c = cv2.approxPolyDP(c.astype(np.int32), 0.9, True)[:, 0, :]
    if len(c) < 3:
        return None
    return "M" + "L".join(f"{x:.0f} {y:.0f}" for x, y in c) + "Z"

# outer outlines in writing order (leftmost first), each followed by its holes (the loops of the
# letters); split into the name and the line under it, so on a phone the name can stand big on top
outer = [i for i, h in enumerate(hier) if h[3] < 0 and cv2.contourArea(contours[i]) > 30]
outer.sort(key=lambda i: contours[i][:, 0, 0].min())
W = ink.shape[1]
signs = {}
for name, keep in (("Adele", lambda cx: cx < 0.31 * W), ("Beauty Clinic", lambda cx: cx >= 0.31 * W)):
    mine = [i for i in outer if keep(contours[i][:, 0, 0].mean())]
    allpts = np.vstack([contours[i][:, 0, :] for i in mine])
    bx0, by0 = allpts.min(0) - pad
    bx1, by1 = allpts.max(0) + pad
    parts = []
    for i in mine:
        for j in [i] + [k for k, h in enumerate(hier) if h[3] == i and cv2.contourArea(contours[k]) > 30]:
            p = path(contours[j] - [bx0, by0])
            if p:
                parts.append(p)
    signs[name] = {"parts": parts, "w": int(bx1 - bx0), "h": int(by1 - by0)}
    print(name, len(parts), "outlines", signs[name]["w"], "x", signs[name]["h"])
with open(os.path.join(here, "../../src/app/neon-logo.ts"), "w") as f:
    f.write("// generated by scripts/media/neon-logo.py from Adele's logo, do not edit\n")
    f.write(f"export const NEON_LOGO: Record<string, {{ parts: string[]; w: number; h: number }}> = {json.dumps(signs)};\n")
